#!/usr/bin/env python3
"""Resumable incremental cube-and-conquer SAT search for good s-colourings of [1,n]
(one long-lived CaDiCaL instance; learned clauses are kept across cubes).

Symmetry breaking (valid lex-leader prefixes for the group generated by
colour reversal C: c -> s+1-c and position reversal R: i -> n+1-i):
  C : chi(1) <= ceil(s/2); chi(1)=mid -> chi(2) <= mid  (mid = (s+1)/2 when s odd)
  R : chi(1) <= chi(n); chi(1)=chi(n) -> chi(2) <= chi(n-1)
  RC: chi(1) <= s+1-chi(n); chi(1)+chi(n)=s+1 -> chi(2) <= s+1-chi(n-1)
usage: sat_inc2.py n s K statefile [solver]
"""
import sys, os, time, itertools
from pysat.solvers import Solver

def var(i, c, s):  # i in [0,n), c in [0,s)  (colour c means printed colour c+1)
    return i * s + c + 1

def build(n, s):
    cl = []
    for i in range(n):
        cl.append([var(i, c, s) for c in range(s)])
        for c1 in range(s):
            for c2 in range(c1 + 1, s):
                cl.append([-var(i, c1, s), -var(i, c2, s)])
    forb = [(a, b, c) for a in range(s) for b in range(s) for c in range(s) if b - a == c - b]
    for d in range(1, (n - 1) // 2 + 1):
        for a in range(0, n - 2 * d):
            for (c1, c2, c3) in forb:
                cl.append([-var(a, c1, s), -var(a + d, c2, s), -var(a + 2 * d, c3, s)])
    # ---- symmetry breaking ----
    L = n - 1
    # C: chi(0) <= (s-1)//2 (0-based colours); if s odd and chi(0)==mid: chi(1) <= mid
    mid = (s - 1) // 2
    cl.append([var(0, c, s) for c in range(mid + 1)])
    if s % 2 == 1:
        cl.append([-var(0, mid, s)] + [var(1, c, s) for c in range(mid + 1)])
    # R: chi(0) <= chi(L)
    for a in range(s):
        for b in range(s):
            if a > b:
                cl.append([-var(0, a, s), -var(L, b, s)])
    # R second level: chi(0)==chi(L) -> chi(1) <= chi(L-1)
    for e in range(s):
        for a in range(s):
            for b in range(s):
                if a > b:
                    cl.append([-var(0, e, s), -var(L, e, s), -var(1, a, s), -var(L - 1, b, s)])
    # RC: chi(0) <= s-1-chi(L)
    for a in range(s):
        for b in range(s):
            if a > s - 1 - b:
                cl.append([-var(0, a, s), -var(L, b, s)])
    # RC second level: chi(0) == s-1-chi(L) -> chi(1) <= s-1-chi(L-1)
    for e in range(s):
        for a in range(s):
            for b in range(s):
                if a > s - 1 - b:
                    cl.append([-var(0, e, s), -var(L, s - 1 - e, s), -var(1, a, s), -var(L - 1, b, s)])
    return cl

def decode(model, n, s):
    col = []
    for i in range(n):
        cs = [c for c in range(s) if model[var(i, c, s) - 1] > 0]
        assert len(cs) == 1
        col.append(cs[0] + 1)
    viol = sum(1 for d in range(1, (n - 1) // 2 + 1) for a in range(0, n - 2 * d)
               if col[a + d] - col[a] == col[a + 2 * d] - col[a + d])
    return col, viol

def main():
    n, s, K, sf = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3]), sys.argv[4]
    name = sys.argv[5] if len(sys.argv) > 5 else "cadical195"
    cl = build(n, s)
    done = set()
    if os.path.exists(sf):
        for line in open(sf):
            if line.strip(): done.add(line.split()[0])
    cubes = [c for c in itertools.product(range(s), repeat=K) if c[0] <= (s - 1) // 2]
    print(f"n={n} s={s} K={K} solver={name} clauses={len(cl)} cubes={len(cubes)} done={len(done)}", flush=True)
    t0 = time.time(); found = 0; ndone = 0
    S = Solver(name=name, bootstrap_with=cl)
    for idx, cube in enumerate(cubes):
        key = "".join(str(c + 1) for c in cube)
        if key in done: continue
        bad = any(cube[a + d] - cube[a] == cube[a + 2 * d] - cube[a + d]
                  for d in range(1, K) for a in range(0, K - 2 * d))
        t1 = time.time()
        if bad:
            res = "BADPREFIX"
        else:
            r = S.solve(assumptions=[var(i, c, s) for i, c in enumerate(cube)])
            if r:
                colr, viol = decode(S.get_model(), n, s)
                found += 1
                res = "SAT " + "".join(map(str, colr)) + f" viol={viol}"
                print(f"CUBE {key}: {res}", flush=True)
            else:
                res = "UNSAT"
        dt = time.time() - t1
        with open(sf, "a") as st:
            st.write(f"{key} {res} {dt:.2f}\n")
        ndone += 1
        print(f"[{idx+1}/{len(cubes)}] {key} {res.split()[0]} {dt:.1f}s elapsed {time.time()-t0:.0f}s", flush=True)
    print(f"ALL CUBES DONE: found={found} total time this run {time.time()-t0:.0f}s", flush=True)

if __name__ == "__main__":
    main()
